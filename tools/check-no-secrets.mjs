#!/usr/bin/env node
// Guard against committing connection secrets. This is a shape-and-assignment
// check, not a full secret scanner: it cannot tell a synthetic fixture UUID from
// a real one, so it relies on documented allowlists plus an inline marker.
//
// Rules
//   1. Private key material (PEM) -- always an error, everywhere.
//   2. A secret-shaped assignment whose right-hand side is a literal: either a
//      quoted string or a high-entropy unquoted blob. Identifier references
//      (`password: auth.password`, `token = this.token`) are not secrets and are
//      never flagged -- the legacy codebase passes credentials around by
//      reference constantly.
//   3. VLESS UUID literals outside fixture-bearing directories. Documentation and
//      contract examples legitimately carry synthetic UUIDs, so docs/**,
//      packages/schema/**, connector/testdata/**, **/test/** and
//      **/examples/** are exempt from rule 3 only -- rules 1 and 2 still apply
//      there.
//   4. A tracked .env file.
//
// Vendored third-party code is skipped entirely: it is not ours to scrub, and
// minified bundles produce noise that would hide real findings.
//
// Suppress a single line with: nexora-secret-allow: <reason>

import { execFileSync } from 'node:child_process';
import { readFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO = resolve(dirname(fileURLToPath(import.meta.url)), '..');

const FIXTURE_PATH_RE =
  /(^|\/)(docs|examples|fixtures|testdata|test|verification)(\/|$)|^packages\/schema\/|\.env\.example$|\.md$/;

const VENDORED_PATH_RE =
  /(^|\/)(node_modules|bower_components|uglifyjs)(\/|$)|(^|\/)lib\/|\.min\.js$|(^|\/)themes\//;

const PLACEHOLDER_RE =
  /^(<|\$\{?|process\.env|%|your[-_]|xxx+$|redacted|changeme|example|sample|dummy|fake|test|fixture|null|true|false|0+|[{}[\]"']*$)/i;

const PEM_RE = /-----BEGIN [A-Z ]*PRIVATE KEY-----/;
const ASSIGN_RE =
  /(?:password|passwd|secret|token|api[_-]?key|private[_-]?key|authorization|cookie)\s*[:=]\s*(["'`]?)([^\s"'`,;)}]{8,})/i;
const UUID_RE = /\b[0-9a-f]{8}-[0-9a-f]{4}-[1-5][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}\b/i;

// A bare identifier, member access, or call -- a reference, not a literal.
const IDENTIFIER_RE = /^[A-Za-z_$][A-Za-z0-9_$.]*$/;
// Something that only occurs in real credentials: long base64/hex-ish blob.
const BLOB_RE = /^[A-Za-z0-9+/_=-]{24,}$/;

// Credentials generated by a service are long and mix character classes; the
// legacy test suite uses short single-class words ('cheesecake', 'password123').
// Flagging the latter would bury real findings, so quoted literals must clear a
// shape bar as well as the placeholder list.
function credentialShaped(value) {
  if (value.length >= 20) return true;
  if (value.length < 12) return false;
  const classes = [/[a-z]/, /[A-Z]/, /[0-9]/, /[^A-Za-z0-9]/].filter((re) => re.test(value));
  return classes.length >= 2;
}

function isLiteralSecret(quote, value) {
  if (PLACEHOLDER_RE.test(value)) return false;
  if (quote) return credentialShaped(value);
  return !IDENTIFIER_RE.test(value) && BLOB_RE.test(value);
}

function classifyLine(line, isFixture) {
  if (line.includes('nexora-secret-allow:')) return null;
  if (PEM_RE.test(line)) {
    return { rule: 'private-key', detail: 'PEM private key material in a tracked file' };
  }
  const assign = line.match(ASSIGN_RE);
  if (assign && !isFixture && isLiteralSecret(assign[1], assign[2])) {
    return { rule: 'secret-assignment', detail: line.trim().slice(0, 90) };
  }
  if (!isFixture && UUID_RE.test(line)) {
    return {
      rule: 'uuid-literal',
      detail: `${line.trim().slice(0, 90)} -- put fixtures under docs/, packages/schema/, ` +
        `connector/testdata/ or add "nexora-secret-allow: <why>"`,
    };
  }
  return null;
}

// The scanner is only a gate if it demonstrably fires. `--selftest` runs the rules
// against embedded positives and negatives so CI proves the guard is not inert.
const SELFTEST = [
  { file: 'src/a.go', line: '  key: "-----BEGIN PRIVATE KEY-----"', want: 'private-key' }, // nexora-secret-allow: gate's own positive
  { file: 'src/a.go', line: 'uuid: "b7a3f1c2-4d5e-4f60-8a9b-0c1d2e3f4a5b"', want: 'uuid-literal' }, // nexora-secret-allow: gate's own positive
  { file: 'docs/x.md', line: 'uuid: "b7a3f1c2-4d5e-4f60-8a9b-0c1d2e3f4a5b"', want: null }, // nexora-secret-allow: gate's own negative
  { file: 'docs/x.md', line: 'password: "aB3dE6fG9hJ2kL5mN8pQ"', want: null }, // nexora-secret-allow: gate's own negative
  {
    file: 'src/a.go',
    line: 'password: "aB3dE6fG9hJ2kL5mN8pQ"', // nexora-secret-allow: gate's own positive
    want: 'secret-assignment',
  },
  { file: 'src/a.go', line: 'token: "ghp_9K2mXvBqL7pR4tWzNcYdEfHjS1uVbQeA"', want: 'secret-assignment' }, // nexora-secret-allow: gate's own positive
  { file: 'src/a.go', line: 'authorization = "Basic " + btoa(creds)', want: null },
  { file: 'src/b.coffee', line: 'password: auth.password', want: null },
  { file: 'src/b.coffee', line: 'token: this.accessToken', want: null },
  { file: 'src/b.coffee', line: "password: 'cheesecake'", want: null },
  { file: 'src/b.coffee', line: 'password: <from-keystore>', want: null },
  { file: 'src/b.coffee', line: "secret: 'REDACTED'", want: null },
  {
    file: 'src/b.coffee',
    line: "privateKey: 'Mt2eN3pQwRvY0kLdA8iFgHjK5oPqRsUv' # nexora-secret-allow: fixture",
    want: null,
  },
];

function runSelftest() {
  const failures = [];
  for (const { file, line, want } of SELFTEST) {
    const got = classifyLine(line, FIXTURE_PATH_RE.test(file))?.rule ?? null;
    if (got !== want) failures.push(`  want ${String(want).padEnd(18)} got ${String(got).padEnd(18)} ${line}`);
  }
  if (failures.length > 0) {
    console.error(`SELFTEST FAILED ${failures.length}/${SELFTEST.length}:`);
    console.error(failures.join('\n'));
    process.exit(1);
  }
  console.log(`SELFTEST OK: ${SELFTEST.length} cases (positives fire, references and fixtures stay quiet).`);
  process.exit(0);
}

if (process.argv.includes('--selftest')) runSelftest();

const findings = [];

function push(file, line, rule, detail) {
  findings.push({ file, line, rule, detail });
}

let files;
try {
  files = execFileSync('git', ['ls-files', '-z'], { cwd: REPO, encoding: 'utf8' })
    .split('\0')
    .filter(Boolean);
} catch (err) {
  console.error('cannot list tracked files:', err.message);
  process.exit(2);
}

let vendoredSkipped = 0;

for (const file of files) {
  if (file === '.env' || (file.startsWith('.') && file.endsWith('.env'))) {
    push(file, 0, 'tracked-env', '.env must never be committed; use .env.example');
    continue;
  }
  if (VENDORED_PATH_RE.test(file)) {
    vendoredSkipped++;
    continue;
  }

  let text;
  try {
    text = await readFile(resolve(REPO, file), 'utf8');
  } catch {
    continue;
  }
  if (text.includes('\0')) continue;

  const isFixture = FIXTURE_PATH_RE.test(file);
  const lines = text.split('\n');

  for (let i = 0; i < lines.length; i++) {
    const found = classifyLine(lines[i], isFixture);
    if (found) push(file, i + 1, found.rule, found.detail);
  }
}

if (findings.length === 0) {
  console.log(
    `OK: no secret-shaped content in ${files.length - vendoredSkipped} files ` +
      `(${vendoredSkipped} vendored/minified files skipped).`,
  );
  process.exit(0);
}

console.error(`FOUND ${findings.length} possible secret(s):`);
for (const f of findings) {
  console.error(`  ${f.file}${f.line ? `:${f.line}` : ''}  [${f.rule}]`);
  console.error(`      ${f.detail}`);
}
console.error(
  '\nIf a finding is a legitimate synthetic fixture, move it to a fixture path ' +
    'or annotate the line with "nexora-secret-allow: <reason>".',
);
process.exit(1);
